$$;

-- Uniform secure random integer in [0, upper) using rejection sampling over pgcrypto bytes
-- (no modulo bias). Used by the game engine to draw outcomes.
create or replace function public.secure_random_int(upper int)
returns int
language plpgsql
volatile
set search_path = ''
as $$
declare
  limit_val bigint;
  r bigint;
  b bytea;
begin
  if upper is null or upper <= 0 then
    raise exception 'secure_random_int: upper must be > 0';
  end if;
  -- largest multiple of upper below 2^32
  limit_val := (4294967296 / upper) * upper;
  loop
    b := extensions.gen_random_bytes(4);
    r := (get_byte(b, 0)::bigint << 24) | (get_byte(b, 1)::bigint << 16)
       | (get_byte(b, 2)::bigint << 8)  |  get_byte(b, 3)::bigint;
    exit when r < limit_val;
  end loop;
  return (r % upper)::int;
end;
$$;

-- SHA-256 hex digest helper (API keys, handoff codes, request hashes are stored hashed only).
create or replace function public.sha256_hex(input text)
returns text
language sql
immutable
set search_path = ''
as $$
  select encode(extensions.digest(convert_to(input, 'UTF8'), 'sha256'), 'hex');
$$;
