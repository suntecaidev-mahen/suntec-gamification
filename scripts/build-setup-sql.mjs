#!/usr/bin/env node
// Concatenates supabase/migrations/*.sql (in filename order) into supabase/setup_all.sql
// so the whole schema can be pasted into the Supabase SQL Editor in one go.
// Run after changing any migration:  npm run db:bundle
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'supabase', 'migrations');
const files = readdirSync(dir).filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort();

const header = `-- =============================================================================
-- Suntec+ Play & Win — CONSOLIDATED SETUP SCRIPT (generated, do not edit by hand)
--
-- Generated by scripts/build-setup-sql.mjs from supabase/migrations/:
${files.map((f) => `--   * ${f}`).join('\n')}
--
-- How to use: Supabase Dashboard → SQL Editor → New query → paste this whole file → Run.
-- Safe to re-run. Then run supabase/seed.sql for demo data (DEV/SIT only).
-- =============================================================================

`;

const body = files
  .map((f) => `\n-- >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>> ${f} >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>\n\n${readFileSync(join(dir, f), 'utf8').trim()}\n`)
  .join('\n');

writeFileSync(join(root, 'supabase', 'setup_all.sql'), header + body);
console.log(`supabase/setup_all.sql written from ${files.length} migration files.`);
